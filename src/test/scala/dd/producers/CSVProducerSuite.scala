package dd.producers

import java.nio.file.Files
import scala.jdk.CollectionConverters.SeqHasAsJava

class CSVProducerSuite extends munit.FunSuite:
  test("CSVProducer loads valid rows and skips malformed ones"):
    val csvFile = Files.createTempFile("dedup2-csv-producer", ".csv")
    Files.write(
      csvFile,
      Seq(
        "id|title",
        "1|First row",
        "2",
        "3|Third row"
      ).asJava
    )

    val producer = new CSVProducer(
      csv = csvFile.toString,
      schema = Map(0 -> "id", 1 -> "title"),
      hasHeader = true
    )

    val documents = producer.getDocuments.toList

    assertEquals(documents.size, 2)
    assertEquals(documents.head.fields, Seq("id" -> "1", "title" -> "First row"))
    assertEquals(documents.last.fields, Seq("id" -> "3", "title" -> "Third row"))

  test("CSVProducer reads quoted comma-separated fields generated by SQL2CSV with fieldSeparator ','"):
    val csvFile = Files.createTempFile("dedup2-csv-producer-quoted", ".csv")
    Files.write(
      csvFile,
      Seq(
        "id,title",
        "1,\"Title with comma, and \"\"quotes\"\"\""
      ).asJava
    )

    val producer = new CSVProducer(
      csv = csvFile.toString,
      schema = Map(0 -> "id", 1 -> "title"),
      hasHeader = true,
      fieldSeparator = ','
    )

    val documents = producer.getDocuments.toList

    assertEquals(documents.size, 1)
    assertEquals(documents.head.fields, Seq("id" -> "1", "title" -> "Title with comma, and \"quotes\""))

  test("CSVProducer reads direct pipe-separated content, with commas and quoted pipes in values"):
    val producer = new CSVProducer(
      csv = "id|title\n1|Inline title, with comma\n2|\"Title | with pipe\"\n",
      schema = Map(0 -> "id", 1 -> "title"),
      hasHeader = true
    )

    val documents = producer.getDocuments.toList

    assertEquals(documents.size, 2)
    assertEquals(documents.head.fields, Seq("id" -> "1", "title" -> "Inline title, with comma"))
    assertEquals(documents.last.fields, Seq("id" -> "2", "title" -> "Title | with pipe"))

  test("CSVProducer uses the pipe by default: a comma-separated file needs fieldSeparator ','"):
    val commaContent = "id,title\n1,First row\n"
    val schema = Map(0 -> "id", 1 -> "title")

    // With the default separator the whole line is one field, so the row is skipped.
    assertEquals(new CSVProducer(commaContent, schema, hasHeader = true).getDocuments.toList, Nil)
    assertEquals(new CSVProducer(commaContent, schema, hasHeader = true, fieldSeparator = ',')
      .getDocuments.toList.map(_.fields), List(Seq("id" -> "1", "title" -> "First row")))
